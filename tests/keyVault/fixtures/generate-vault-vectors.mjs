/**
 * Regenerates vault-v1-vectors.json from node:crypto ONLY (Node >= 24.7 for
 * crypto.argon2Sync) — an implementation independent of src/keyVault, so the
 * known-answer tests check core against something other than itself.
 * All inputs are fixed throwaway values; nothing here is a real secret.
 *
 *   node tests/keyVault/fixtures/generate-vault-vectors.mjs
 */
import { argon2Sync, createCipheriv, createHash, hkdfSync } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const b64url = (buf) => Buffer.from(buf).toString('base64url');
const hex = (buf) => Buffer.from(buf).toString('hex');
const bytes = (start, length) => Buffer.from(Array.from({ length }, (_, i) => (start + i) & 0xff));

function gcm(key, nonce, plaintext, aad) {
  const cipher = createCipheriv('aes-256-gcm', key, nonce);
  cipher.setAAD(Buffer.from(aad, 'utf8'));
  const ct = Buffer.concat([cipher.update(plaintext), cipher.final(), cipher.getAuthTag()]);
  return { n: b64url(nonce), ct: b64url(ct) };
}

// "ｐａｓｓ" fullwidth + "ﬁ" ligature + "é" decomposed: NFKC makes it "passfié".
const passphrase = 'ｐａｓｓﬁé';
const normalized = passphrase.normalize('NFKC');
const kdf = { alg: 'argon2id', m: 65536, t: 3, p: 1, salt: b64url(bytes(0x10, 16)) };
const mk = argon2Sync('argon2id', {
  message: Buffer.from(normalized, 'utf8'),
  nonce: bytes(0x10, 16),
  parallelism: 1,
  tagLength: 32,
  memory: 65536,
  passes: 3,
});
const kek = Buffer.from(hkdfSync('sha256', mk, Buffer.alloc(0), 'pocketshell-vault/v1/kek', 32));
const auth = Buffer.from(hkdfSync('sha256', mk, Buffer.alloc(0), 'pocketshell-vault/v1/auth', 32));

const vaultId = b64url(bytes(0x20, 16));
const dek = bytes(0x40, 32);
const sshKeyId = b64url(createHash('sha256').update(Buffer.from('fixture public key blob')).digest().subarray(0, 16));
const passwordKeyId = b64url(bytes(0x90, 16));
const index = {
  keys: [
    { keyId: sshKeyId, name: 'fixture key', type: 'ssh-ed25519', fingerprint: 'SHA256:' + 'A'.repeat(43), createdAt: '2026-10-15T00:00:00.000Z' },
    { keyId: passwordKeyId, name: 'fixture password', type: 'password', createdAt: '2026-10-15T00:00:00.000Z' },
  ],
  hosts: {
    hetzner: { keyId: sshKeyId, gatewayAuth: 'both' },
    nas: { keyId: passwordKeyId, gatewayAuth: 'host' },
  },
  sync: { passphrase: 'fixture sync passphrase' },
};
const indexJson = JSON.stringify(index);

const header = {
  v: 1,
  vaultId,
  kdf,
  wrappedDek: gcm(kek, bytes(0x60, 12), dek, 'pocketshell-vault/v1/dek|' + vaultId),
  check: gcm(kek, bytes(0x70, 12), Buffer.from('pocketshell-vault-check-v1', 'utf8'), 'pocketshell-vault/v1/check|' + vaultId),
  index: gcm(dek, bytes(0x80, 12), Buffer.from(indexJson, 'utf8'), 'pocketshell-vault/v1/index|' + vaultId),
  epoch: 1,
  updatedAt: '2026-10-15T00:00:00.000Z',
};

const keyPlaintext = '-----BEGIN FIXTURE (not a key)-----\nAAAA\n-----END FIXTURE (not a key)-----\n';
const pubLine = 'ssh-ed25519 Zml4dHVyZSBwdWJsaWMga2V5IGJsb2I=';
const keySealed = gcm(dek, bytes(0xa0, 12), Buffer.from(keyPlaintext, 'utf8'), `pocketshell-vault/v1/key|${vaultId}|${sshKeyId}`);
const keyBlob = {
  v: 1, vaultId, keyId: sshKeyId, ...keySealed,
  pub: gcm(dek, bytes(0xb0, 12), Buffer.from(pubLine, 'utf8'), `pocketshell-vault/v1/pub|${vaultId}|${sshKeyId}`),
};
const passwordPlaintext = 'fixture host password';
const passwordBlob = {
  v: 1, vaultId, keyId: passwordKeyId,
  ...gcm(dek, bytes(0xc0, 12), Buffer.from(passwordPlaintext, 'utf8'), `pocketshell-vault/v1/key|${vaultId}|${passwordKeyId}`),
};

const vectors = {
  comment: 'Vault v1 known-answer vectors, generated by generate-vault-vectors.mjs from node:crypto only. Throwaway values.',
  passphrase,
  normalizedPassphrase: normalized,
  kdf,
  mkHex: hex(mk),
  kekHex: hex(kek),
  authHex: hex(auth),
  authB64url: b64url(auth),
  vaultId,
  dekHex: hex(dek),
  indexJson,
  header,
  headerSlotData: JSON.stringify(header),
  sshKey: { keyId: sshKeyId, plaintext: keyPlaintext, publicKey: pubLine, blob: keyBlob, slotData: JSON.stringify(keyBlob) },
  password: { keyId: passwordKeyId, plaintext: passwordPlaintext, blob: passwordBlob, slotData: JSON.stringify(passwordBlob) },
};
writeFileSync(new URL('./vault-v1-vectors.json', import.meta.url), JSON.stringify(vectors, null, 2) + '\n');
